def test_sets_artifacts_exist():
    for path in (INDEX_PATH, UNION_PATH, FIXTURE_DIR / "set.json"):
        assert path.is_file(), f"{path} is missing — run the generator"


def test_registry_declares_the_shipped_set_and_the_fixture_set():
    index = _json(INDEX_PATH)
    by_id = {entry["id"]: entry for entry in index["sets"]}
    # The shipped set is really named Technology (owner ruling, #17): id, display
    # name and version are its identity; only the DIRECTORY keeps the historical
    # `prompts/generated/` name.
    assert index["default_set"] == "technology"
    assert by_id["technology"]["kind"] == "shipped"
    assert by_id["technology"]["name"] == "Technology"
    assert re.fullmatch(r"\d+\.\d+\.\d+", by_id["technology"]["version"])
    assert by_id["technology"]["dir"] == "prompts/generated"
    # The second set is declared test scaffolding, not a shipped vocabulary.
    assert by_id["fixture-core"]["kind"] == "fixture"
    assert by_id["fixture-core"]["dir"] == "prompts/sets/fixture-core"
    assert by_id["fixture-core"]["spec"].endswith("prompts/sets/fixture-core/library.spec.json")


def test_core_is_the_four_infrastructure_components_and_the_panels_are_separate():
    index = _json(INDEX_PATH)
    assert index["core_components"] == list(dsl_spec.CORE_COMPONENT_NAMES)
    assert tuple(index["core_components"]) == dsl_sets.core_component_names()
    # Engine-emitted panels: client panel registry only, never narrator-taught
    # (ADR-004) — so no narrator set can add or remove them.
    # AssistantCard is a client panel-registry component; EnvTracker is parsed and
    # rendered by ChatHud itself (never an openui registry entry). Neither is a
    # narrator component, so no set can carry or drop them.
    assert "name: 'AssistantCard'" in PANEL_REGISTRY_PATH.read_text(encoding="utf-8")
    assert (REPO_ROOT / "frontend" / "src" / "lib" / "openui" / "components" / "EnvTracker.svelte").is_file()
    assert "EnvTracker" in (REPO_ROOT / "frontend" / "src" / "routes" / "chat" / "ChatHud.svelte").read_text(encoding="utf-8")
    for name in index["panel_components"]:
        assert name not in _json(DEFAULT_DIR / "library.spec.json")["components"], name
        assert name not in dsl_sets.union_component_names(), name
        for entry in index["sets"]:
            assert name not in entry["components"], (name, entry["id"])


def test_every_declared_set_is_loadable():
    """(c) set ⊆ union = loadable — the machine-check, over the shipped registry."""
    entries = dsl_sets.component_sets()
    assert {entry.id for entry in entries} == {"technology", "fixture-core"}
    for entry in entries:
        verdict = dsl_sets.set_loadability(entry)
        assert verdict.ok, (entry.id, verdict.reason)
        assert verdict.checked is True
        assert verdict.unrenderable == ()
    assert set(dsl_sets.loadable_set_ids()) == {"technology", "fixture-core"}


def test_a_component_outside_the_union_is_refused_with_a_readable_reason():
    verdict = dsl_sets.check_set_loadable(["ScenePane", "Widget"])
    assert verdict.ok is False
    assert verdict.unrenderable == ("Widget",)
    assert "Widget" in verdict.reason and "subset" in verdict.reason


def test_the_union_is_what_the_client_can_render():
    """The union names are exactly the registry names minus render-only aliases."""
    union = set(dsl_sets.union_component_names())
    assert union, "union spec is empty — run the generator"
    assert union == set(_json(DEFAULT_DIR / "library.spec.json")["components"])
    aliases = dict(dsl_sets.render_aliases())
    assert set(aliases) <= _registry_names()
    assert not (set(aliases) & union)
    assert _registry_names() - set(aliases) == union


def test_shipped_set_artifacts_match_the_registry_entry():
    """The registry's shipped entry describes the committed artifacts, byte-for-byte."""
    entry = dsl_sets.component_set("technology")
    assert entry is not None
    spec_bytes = (DEFAULT_DIR / "library.spec.json").read_bytes()
    expected = hashlib.sha256(spec_bytes).hexdigest()[:12]
    assert entry.spec_version == expected
    assert set(entry.components) == set(_json(DEFAULT_DIR / "library.spec.json")["components"])
    assert entry.directory == DEFAULT_DIR
    assert entry.name == _json(DEFAULT_DIR / "set.json")["name"]


def test_the_fixture_set_is_a_strict_loadable_subset_carrying_the_core():
    fixture = dsl_sets.component_set("fixture-core")
    assert fixture is not None and fixture.is_fixture
    union = set(dsl_sets.union_component_names())
    assert set(fixture.components) < union
    assert set(dsl_spec.CORE_COMPONENT_NAMES) <= set(fixture.components)
    assert INACTIVE_COMPONENT in union and INACTIVE_COMPONENT not in fixture.components
    # The fixture ships a real, self-consistent set directory.
    manifest = _json(fixture.manifest_path)
    assert manifest["id"] == "fixture-core"
    assert manifest["components"] == list(fixture.components)
    assert fixture.doc_path.is_file() and fixture.doc_path.read_text(encoding="utf-8").strip()


def test_the_active_set_is_renderable():
    """No shipped configuration teaches a component the client cannot render."""
    assert dsl_sets.active_set_id() == "technology"
    assert dsl_sets.active_set_unrenderable() == ()


def test_generator_check_covers_the_sets_tree():
    """`--check` is the artifact-sync oracle for the sets tree too."""
    if shutil.which("node") is None:
        pytest.skip("node not available")
    if not (REPO_ROOT / "frontend" / "node_modules" / "@openuidev" / "lang-core").is_dir():
        pytest.skip("@openuidev/lang-core not installed")
    result = subprocess.run(
        ["node", str(GENERATOR), "--check"],
        cwd=REPO_ROOT / "frontend",
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    for label in (
        "library.spec.json",
        "library.doc.txt",
        "set.json",
        "prompts/sets/union.spec.json",
        "prompts/sets/index.json",
        "prompts/sets/fixture-core/library.spec.json",
    ):
        assert f"ok {label}" in result.stdout, result.stdout


