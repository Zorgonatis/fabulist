def _write_set(directory: Path, components: dict[str, object]) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "library.spec.json").write_text(
        json.dumps({"root": "ScenePane", "components": components}), encoding="utf-8"
    )
    (directory / "library.doc.txt").write_text("Reference.\n", encoding="utf-8")
    return directory


def test_a_set_that_omits_infrastructure_still_gates_it(monkeypatch, tmp_path):
    """The engine force-merges the four, so a set cannot remove core by omission."""
    directory = _write_set(
        tmp_path / "narrow", {"Document": {"props": [{"name": "body", "type": "string"}]}}
    )
    _activate(monkeypatch, directory)
    for name in dsl_spec.CORE_COMPONENT_NAMES:
        assert name in component_names(), name
    assert "Document" in component_names()


def test_every_declared_set_carries_the_core():
    """The generator throws when a set drops a core component, so no declared set
    can omit one — every emitted set carries all four."""
    index = _json(INDEX_PATH)
    core = set(index["core_components"])
    for entry in index["sets"]:
        assert core <= set(entry["components"]), entry["id"]
    assert core == set(dsl_spec.CORE_COMPONENT_NAMES)


def test_a_missing_union_artifact_is_unchecked_not_a_refusal(monkeypatch, tmp_path):
    """A fresh checkout (no generated tree) must not refuse every set."""
    monkeypatch.setenv(dsl_sets.SETS_DIR_ENV_VAR, str(tmp_path / "absent"))
    dsl_sets.reset_sets_cache()
    verdict = dsl_sets.check_set_loadable(["ScenePane", "Anything"])
    assert verdict.ok is True and verdict.checked is False
    assert "no union spec" in verdict.reason
