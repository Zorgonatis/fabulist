def test_the_active_set_is_the_only_taught_vocabulary(monkeypatch):
    """With the fixture active: gate table, doc, strip list and segmenter agree."""
    _activate(monkeypatch, FIXTURE_DIR)
    fixture = dsl_sets.component_set("fixture-core")
    assert fixture is not None

    # the gate table + the strip/segmenter name list (the gate table also carries
    # the render-only legacy alias, which is never part of a set)
    aliases = set(dict(dsl_sets.render_aliases()))
    assert set(component_names()) - aliases == set(fixture.components)
    # the taught doc is the fixture's own artifact, bytes for bytes
    assert library_mini.render_library_doc() == fixture.doc_path.read_text(encoding="utf-8")
    assert "Mindscape" not in library_mini.render_library_doc()
    assert INACTIVE_COMPONENT not in component_names()


def test_the_default_set_teaches_the_full_vocabulary():
    aliases = set(dict(dsl_sets.render_aliases()))
    assert set(component_names()) - aliases == set(dsl_sets.union_component_names())
    assert INACTIVE_COMPONENT in component_names()
    assert INACTIVE_COMPONENT in library_mini.render_library_doc()


def test_an_inactive_component_is_unknown_to_the_engine_but_renders_client_side(monkeypatch):
    """(d) the inactive set's component still renders; the engine degrades visibly."""
    # 1. the union (the render contract) carries it, and the client registers it
    assert INACTIVE_COMPONENT in dsl_sets.union_component_names()
    assert INACTIVE_COMPONENT in _json(UNION_PATH)["components"]
    assert INACTIVE_COMPONENT in _registry_names()

    # 2. activate the fixture set: the engine no longer knows the component
    _activate(monkeypatch, FIXTURE_DIR)
    assert INACTIVE_COMPONENT not in component_names()
    # …the strip helper keeps the statement raw (it is not ours to eat)…
    assert strip_dsl(INACTIVE_STATEMENT) == INACTIVE_STATEMENT
    # …the statement recognizer does not class it as DSL…
    assert statement_like_re().match(INACTIVE_STATEMENT) is None
    assert component_stmt_re().match(INACTIVE_STATEMENT) is None
    # …and the narrate segmenter degrades the line to prose.
    from fabulist.graph.nodes import segment_narrative

    raw = f"He counts.\n{INACTIVE_STATEMENT}\nThe lights hold."
    assert [segment["kind"] for segment in segment_narrative(raw)] == ["prose"]

    # 3. a NEW emission is flagged, never silently accepted
    from fabulist.graph.validation import validate_dsl

    report = validate_dsl([{"kind": "dsl", "text": INACTIVE_STATEMENT}])
    assert report.ok is False
    assert [error.code for error in report.errors] == ["unknown_component"]
    # The failed statement is kept verbatim (ADR-017: keep + tag, never drop).
    assert report.segments == [{"kind": "dsl", "text": INACTIVE_STATEMENT}]


def test_the_inactive_component_parses_against_the_union_and_not_the_fixture_schema():
    """(d) the renderer's own parser: union ⇒ a panel, fixture-only ⇒ unknown.

    Builds the ``LibraryJSONSchema`` lang-core's ``createParser`` consumes (the
    exact call ``library.ts`` makes: ``createParser(library.toJSONSchema())``)
    from the generated specs, and parses the same statement both ways.
    """
    if shutil.which("node") is None:
        pytest.skip("node not available")
    if not (REPO_ROOT / "frontend" / "node_modules" / "@openuidev" / "lang-core").is_dir():
        pytest.skip("@openuidev/lang-core not installed")

    union = _parse_with_schema(UNION_PATH, keep=None)
    assert union["root"] == INACTIVE_COMPONENT
    assert union["errors"] == []

    fixture_spec = FIXTURE_DIR / "library.spec.json"
    keep = list(_json(fixture_spec)["components"])
    reduced = _parse_with_schema(fixture_spec, keep=keep)
    assert reduced["root"] is None
    assert "unknown-component" in reduced["errors"]


_NODE_PARSE = """
import { createParser } from '@openuidev/lang-core';
import { readFileSync } from 'node:fs';

const spec = JSON.parse(readFileSync(process.env.FABULIST_SPEC, 'utf8'));
const keep = process.env.FABULIST_KEEP ? new Set(process.env.FABULIST_KEEP.split(',')) : null;
const defs = {};
const properties = {};
for (const [name, comp] of Object.entries(spec.components)) {
	if (keep && !keep.has(name)) continue;
	const deep = comp.jsonSchema;
	const coarse = {
		type: 'object',
		properties: Object.fromEntries(
			comp.props.map((prop) => [
				prop.name,
				{ type: prop.type === 'number' ? 'number' : prop.type.endsWith('[]') ? 'array' : 'string' }
			])
		),
		required: comp.props.filter((prop) => prop.required).map((prop) => prop.name)
	};
	defs[name] = deep ?? coarse;
	properties[name] = defs[name];
}
const parser = createParser({ $defs: defs, properties });
const result = parser.parse(process.env.FABULIST_STMT);
console.log(
	JSON.stringify({
		root: result.root?.typeName ?? null,
		errors: (result.meta?.errors ?? []).map((error) => error.code)
	})
);
"""


def _parse_with_schema(spec_path: Path, *, keep: list[str] | None) -> dict:
    env = dict(os.environ)
    env["FABULIST_SPEC"] = str(spec_path)
    env["FABULIST_KEEP"] = ",".join(keep) if keep is not None else ""
    env["FABULIST_STMT"] = INACTIVE_STATEMENT
    result = subprocess.run(
        ["node", "--input-type=module", "-e", _NODE_PARSE],
        cwd=REPO_ROOT / "frontend",
        capture_output=True,
        text=True,
        env=env,
    )
    assert result.returncode == 0, result.stderr
    return json.loads(result.stdout.strip().splitlines()[-1])


