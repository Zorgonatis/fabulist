"""Component sets: the renderer's union vs the model's active set (issue #15).

The ruling: the RENDERER understands every shipped set (the union — an old
transcript keeps rendering the components of a set that is no longer active),
while the MODEL is taught ONLY the active set (its doc, gate table, strip list
and segmenter all read that set's directory). A set is loadable iff its
components are a subset of the union — the machine-checkable form of "the client
can render it". Infrastructure is core by definition: always present, always
merged, never removable.

This module pins the four seams that make that true:

  * the generated SETS registry (``prompts/sets/index.json``) and union spec
    (``prompts/sets/union.spec.json``) agree with the shipped default artifacts
    and with the frontend render registry (``library.ts``);
  * the engine's taught vocabulary is the ACTIVE set only — with the fixture set
    active, an inactive-set component is unknown to the gate, the strip list and
    the segmenter;
  * that same inactive-set component still RENDERS: the union declares it, the
    client registry registers it, and lang-core's own parser (the renderer's
    parse step) accepts the statement against the union schema and rejects it
    against the fixture set's schema;
  * infrastructure survives a set that omits it (the engine force-merges it), so
    a set can never remove a core component by omission.

The fixture set recipe
----------------------
``prompts/sets/fixture-core/`` is generated by the same generator as the default
(``SETS`` in ``frontend/scripts/generate-library-spec.mjs``): the four
infrastructure components plus ``Custom`` and ``Document`` — a strict,
loadable subset of the union, marked ``kind: "fixture"`` in the registry and
declared test scaffolding only. It is never selected by the default resolution
(the store's default is ``prompts/generated``) and it ships the reference block
only (``craft: false``), because the authored craft sections name components a
subset does not teach. Regenerate with::

    cd frontend && node scripts/generate-library-spec.mjs

and point the engine at it in a test with
``FABULIST_LIBRARY_ARTIFACT_DIR=prompts/sets/fixture-core``.
"""

