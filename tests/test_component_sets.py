from fabulist.prompts import library_mini
from fabulist.prompts.library_mini import reset_library_artifact_cache

REPO_ROOT = Path(__file__).resolve().parents[1]
SETS_DIR = REPO_ROOT / "prompts" / "sets"
INDEX_PATH = SETS_DIR / "index.json"
UNION_PATH = SETS_DIR / "union.spec.json"
DEFAULT_DIR = REPO_ROOT / "prompts" / "generated"
FIXTURE_DIR = SETS_DIR / "fixture-core"
REGISTRY_PATH = REPO_ROOT / "frontend" / "src" / "lib" / "openui" / "library.ts"
PANEL_REGISTRY_PATH = REPO_ROOT / "frontend" / "src" / "lib" / "openui" / "panelLibrary.ts"
GENERATOR = REPO_ROOT / "frontend" / "scripts" / "generate-library-spec.mjs"

#: A component the fixture set does NOT teach, but the client renders.
INACTIVE_COMPONENT = "Mindscape"
INACTIVE_STATEMENT = (
    'mind = Mindscape("Forty Seconds of Calm", '
    '[{text: "the math says run", weight: 55, kind: "thought"}], "dots", "", "resolve")'
)


@pytest.fixture(autouse=True)
def _clean_caches(monkeypatch):
    """No ambient env, no warm caches: every test states its own set."""
    for name in (SPEC_ENV_VAR, ARTIFACT_DIR_ENV_VAR, FLAVORS_ENV_VAR, dsl_sets.SETS_DIR_ENV_VAR):
        monkeypatch.delenv(name, raising=False)
    dsl_spec.reset_spec_cache()
    reset_library_artifact_cache()
    dsl_sets.reset_sets_cache()
    yield
    dsl_spec.reset_spec_cache()
    reset_library_artifact_cache()
    dsl_sets.reset_sets_cache()


def _activate(monkeypatch, directory: Path) -> None:
    """Point the engine at one set directory (the resolution it already honours)."""
    monkeypatch.setenv(ARTIFACT_DIR_ENV_VAR, str(directory))
    dsl_spec.reset_spec_cache()
    reset_library_artifact_cache()


def _json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _registry_names() -> set[str]:
    """Component names declared via ``defineComponent({ name: '…' })``."""
    source = REGISTRY_PATH.read_text(encoding="utf-8")
    return set(re.findall(r"\bname:\s*'([A-Za-z_]\w*)'", source))


