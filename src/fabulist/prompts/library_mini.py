def _load_flavors() -> list[dict]:
    """Lazy-load the VTK flavor entries from ``flavors.json`` (cached).

    Same resolution rule as the validation gate (env override wins, repo-root
    relative), so the narrator's vocabulary and the validator's spec table can
    never drift apart in shape. Missing file -> empty list (only the four code
    components remain in :func:`component_names`' fallback).
    """
    global _FLAVORS_CACHE
    if _FLAVORS_CACHE is None:
        path = resolve_flavors_path()
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            _FLAVORS_CACHE = list(data.get("flavors", []))
        except (OSError, ValueError):
            _FLAVORS_CACHE = []
    return _FLAVORS_CACHE


_FLAVORS_CACHE: list[dict] | None = None


def reset_library_artifact_cache() -> None:
    """Drop the doc / name / flavors caches and re-read the active set.

    The flavors mirror is cleared too (R2 fold P2-4): it feeds the fallback
    component-name list, so a test (or deployment) that repoints
    ``FABULIST_FLAVORS_JSON`` must not keep reading the old mirror.
    """
    global _GENERATED_DOC_CACHE, _COMPONENT_NAMES_CACHE, _FLAVORS_CACHE
    _GENERATED_DOC_CACHE = None
    _COMPONENT_NAMES_CACHE = None
    _FLAVORS_CACHE = None
    library_store().reload()


def _generated_library_doc() -> str | None:
    """The generated doc bytes, or ``None`` when the artifact is absent/empty."""
    global _GENERATED_DOC_CACHE
    snapshot = library_store().snapshot()
    if _GENERATED_DOC_CACHE is None or _GENERATED_DOC_CACHE[0] != snapshot.version:
        _GENERATED_DOC_CACHE = (snapshot.version, snapshot.doc)
    return _GENERATED_DOC_CACHE[1]


def _spec_component_names() -> tuple[str, ...] | None:
    """Component names from the active set's spec, or ``None`` when unavailable."""
    global _COMPONENT_NAMES_CACHE
    snapshot = library_store().snapshot()
    if _COMPONENT_NAMES_CACHE is None or _COMPONENT_NAMES_CACHE[0] != snapshot.version:
        names = component_names_in(snapshot.spec) if snapshot.spec is not None else ()
        _COMPONENT_NAMES_CACHE = (snapshot.version, names or None)
    return _COMPONENT_NAMES_CACHE[1]


def component_names() -> tuple[str, ...]:
    """Every component the narrator may emit, from the generated spec.

    Falls back to the four code components plus the ``flavors.json`` mirror
    when the generated spec is missing (e.g. a fresh checkout before the
    generator is run). This is the single list consumed by
    :data:`fabulist.prompts.compiler._COMPONENT_STMT_RE`.
    """
    names = _spec_component_names()
    if names:
        return names
    fallback = [comp.name for comp in MINI_COMPONENTS]
    for flavor in _load_flavors():
        name = flavor.get("component")
        if name and name not in fallback:
            fallback.append(name)
    return tuple(fallback)


def _required_library_doc() -> str:
    """The generated narrator doc, or a loud error naming how to regenerate it.

    This is the self-resolving value of the ``{{library_doc}}`` variable (D35):
    the surface expression resolves to it without reading any preset surface, so
    a preset whose ``library_doc`` surface is exactly ``{{library_doc}}`` never
    references itself. There is no hand-authored fallback — a missing artifact
    is a broken checkout, not a doc to serve from code.
    """
    generated = _generated_library_doc()
    if generated is not None:
        return generated
    artifact = library_store().snapshot().directory / DOC_FILENAME
    raise ComponentSetError(
        f"narrator library doc {artifact} is missing or unreadable — regenerate "
        "the component artifacts with: cd frontend && node scripts/generate-library-spec.mjs"
    )


def render_library_doc(
    preset_doc: str | None = None,
    variables: Mapping[str, str] | None = None,
) -> str:
    """The model-facing component documentation block the narrator prompt embeds.

    Resolution order:

    1. ``preset_doc`` when supplied (the active preset's ``library_doc`` D27
       surface) — its ``{{expression}}`` tokens resolve against ``variables``
       (unknown tokens stay literal, matching
       :func:`fabulist.prompts.variables.render_template`). D35: the
       ``{{library_doc}}`` token is self-resolving — it always expands to the
       generated doc (:func:`_required_library_doc`) even when the caller
       passes no / an incomplete ``variables`` map, so a literal token never
       reaches the model. Content with no expression is a pure override (no doc
       injected).
    2. the GENERATED doc artifact (``prompts/generated/library.doc.txt``),
       produced from the component spec by ``@openuidev/lang-core``. It is the
       only source: a missing/unreadable artifact raises
       :class:`~fabulist.dsl.store.ComponentSetError` naming the file and the
       generator command, never a stale hand-written doc.
    """
    if preset_doc is not None:
        from .surfaces import render_surface_text

        # D35: resolve the reserved self-expression before the unknown-var
        # literal pass. The caller's ``variables`` wins when it carries the
        # name (production always resolves it via resolve_variables), but a
        # direct/partial call still expands it — a literal `{{library_doc}}`
        # reaching the model would be a bug.
        effective = dict(variables or {})
        effective.setdefault("library_doc", _required_library_doc())
        return render_surface_text(preset_doc, effective)
    return _required_library_doc()


def resolve_library_doc(
    surfaces: Mapping[str, object] | None = None,
    variables: Mapping[str, str] | None = None,
) -> str:
    """Effective library doc: the preset surface when present, generated otherwise.

    The one loader the wiring seam calls for the ``library`` module's content
    (and for the default compiler path), so the surface override and the
    generated doc can never diverge between call sites.

    D35: a surface whose content is the expression ``{{library_doc}}`` (the
    factory default) resolves to the generated doc through
    :func:`render_library_doc`; an owner adds their own top/tail text around
    that token, and content with no token at all is a pure override (their text
    only, no doc injected).
    """
    from .surfaces import normalize_surfaces

    normalized = normalize_surfaces(surfaces)
    if "library_doc" in normalized:
        return render_library_doc(normalized["library_doc"], variables)
    return render_library_doc()
