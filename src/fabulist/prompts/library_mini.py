"""Data definitions for the mini OpenUI component library (PLAN W1.2 / D6; full port W2.4; Wave 2a cull).

Components matching the shared engine contract and the verified W0.4 spike
(``spikes/openui-spike/``). OpenUI Lang statements are "identifier = Component(arg, arg)"
with strictly positional arguments in the order listed below; the entry point is named
``root``. Only what is reachable from ``root`` renders.

The library is the four infrastructure/default components plus ten scene
flavors, the Custom escape hatch and five artifact reproductions (2026-10-14)
flavors — the survivors of the Wave 2a design cull. The flavor list is merged
from ``frontend/src/lib/openui/schemas/flavors.json`` (the zod
single-source-of-truth mirror), so the narrator's doc and the validator's spec
table never drift apart.

Generated artifact (lang-core pipeline, owner mandate)
-----------------------------------------------------
``render_library_doc`` is the single source the narrator prompt embeds. Its
content is now GENERATED by ``@openuidev/lang-core`` from the component spec
the frontend registry is derived from — written by
``frontend/scripts/generate-library-spec.mjs`` to two checked-in artifacts:

* ``prompts/generated/library.spec.json`` — the ``LibrarySpec`` (14 components +
  component groups + per-component prop metadata).
* ``prompts/generated/library.doc.txt`` — the generated narrator library doc
  (this module just loads it).

The spec additionally drives :func:`component_names`, which
:mod:`fabulist.prompts.compiler` turns into the DSL-stripping regex — that is
how every flavor name (not just the four generics) is stripped from narrator
history. There is ONE source: the generated artifact. A checkout without it
raises a loud, actionable error naming the file and the generator command —
this module carries no hand-written doc to serve instead.

The ACTIVE set only (issue #15). Both artifacts are read from the store's
snapshot, i.e. from the ACTIVE set's directory (``prompts/generated/`` for the
shipped default, ``prompts/sets/<id>/`` for any other set) — never from the
union. The renderer may know a wider vocabulary than the model does, by design:
a transcript keeps rendering components of a set that is no longer active, while
the taught doc carries only what the active set teaches. A set swap therefore
changes these bytes on the next turn, which is one full prompt-prefix re-prefill
(the doc sits in the stable prefix) — accepted in ADR-025.
"""

