"""Component sets: the renderer's union, the model's active set (issue #15).

One ruling, two vocabularies:

* **The renderer understands every shipped set** — the UNION. A transcript
  written while set A was active keeps rendering A's components after set B is
  active, because the client registers every renderer it has ever shipped and
  re-splits prose with that registry (``frontend/src/routes/chat/segment.ts``).
* **The model is taught exactly one set** — the ACTIVE one. The taught doc, the
  gate table, the strip list and the server-side segmenter all read the active
  set's directory through :mod:`fabulist.dsl.store`; there is no second source
  and no merge of inactive sets into the taught vocabulary.
* **A set is loadable iff its components ⊆ the union** — the machine-checkable
  form of "the client can render it" (:func:`check_set_loadable`). The generator
  runs the same check when it emits the artifacts, and the selection door
  (``POST /api/sessions/{sid}/component-set``) refuses a non-loadable set with
  this module's reason and the offending names.
* **Infrastructure is core by definition**: always present, always merged, never
  removable (:data:`fabulist.dsl.spec.CORE_COMPONENT_NAMES`; the engine's gate
  table force-merges the four into every set). The engine-emitted panels
  (``EnvTracker``, ``AssistantCard``) are not narrator components at all, so no
  narrator set can add or remove them: ``AssistantCard`` is registered in the
  client's separate ``panelLibrary.ts`` registry and ``EnvTracker`` is parsed and
  rendered by ``ChatHud`` itself (ADR-004 — the HUD is deliberately absent from
  the narrator library). The registry records both as always-present core.

Artifacts (generated by ``frontend/scripts/generate-library-spec.mjs``; never
hand-edited)::

    prompts/sets/index.json        # the registry read by this module
    prompts/sets/union.spec.json   # the render contract (every renderable component)
    prompts/sets/<id>/...          # any set whose directory is not prompts/generated

The shipped set is the TECHNOLOGY set (``id: "technology"``, version ``1.0.0``,
ADR-024); it keeps the historical ``prompts/generated/`` directory, because a
directory name is a path rather than an identity. It *is* the current full
vocabulary, and its spec/doc bytes are unchanged by the rename. Any other set is a
directory of the same three files (``set.json``, ``library.spec.json``,
``library.doc.txt``); ``prompts/sets/fixture-core/`` ships as test scaffolding so
the active/union split is exercised by real artifacts rather than mocks.

SELECTION IS PER-SESSION (issues #16/#24, owner ruling). A swap is a session
log fact — the latest ``set_swapped`` row in the session's fork-aware chain —
and :func:`session_snapshot` resolves it to a set directory and binds that
directory in the shared component store. The store caches CONTENT per directory
(one snapshot shared by every session on the same set); it holds no
global selection. :func:`active_set` remains the off-turn/current-context view
(env override → the running session's set → the default).

Cache: the index and the union spec are re-read when their ``(mtime, size)``
moves, so a regenerated tree is live without a restart — the same discipline the
component store applies to the set artifacts themselves.
"""

