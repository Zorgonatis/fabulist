#: Env override for the sets tree (tests / deployments; never needed in prod).
SETS_DIR_ENV_VAR = "FABULIST_COMPONENT_SETS_DIR"
INDEX_FILENAME = "index.json"
UNION_SPEC_FILENAME = "union.spec.json"

_REPO_ROOT = Path(__file__).resolve().parents[3]


def _repo_root() -> Path:
    return _REPO_ROOT


def sets_dir() -> Path:
    """The component-sets tree (``FABULIST_COMPONENT_SETS_DIR`` wins)."""
    override = os.environ.get(SETS_DIR_ENV_VAR)
    if override:
        return Path(override)
    return _repo_root() / "prompts" / "sets"


def index_path() -> Path:
    """Path to the generated sets registry."""
    return sets_dir() / INDEX_FILENAME


def union_spec_path() -> Path:
    """Path to the generated union spec (the render contract)."""
    return sets_dir() / UNION_SPEC_FILENAME


def _stamp(path: Path) -> tuple[int, int] | None:
    try:
        stat = path.stat()
    except OSError:
        return None
    return (stat.st_mtime_ns, stat.st_size)


def _read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _resolve(entry: Any) -> Path:
    path = Path(str(entry))
    return path if path.is_absolute() else _repo_root() / path


@dataclass(frozen=True)
class ComponentSetEntry:
    """One declared set: what it teaches and where its artifacts live."""

    id: str
    name: str
    kind: str
    directory: Path
    components: tuple[str, ...]
    #: The set's own identity version from the registry/manifest (e.g. ``1.0.0``),
    #: distinct from the store's ``ComponentSetSnapshot.version`` reload counter.
    version: str = ""
    spec_version: str = ""

    @property
    def is_fixture(self) -> bool:
        """Test scaffolding rather than a shipped vocabulary."""
        return self.kind == "fixture"

    @property
    def spec_path(self) -> Path:
        return self.directory / "library.spec.json"

    @property
    def doc_path(self) -> Path:
        return self.directory / "library.doc.txt"

    @property
    def manifest_path(self) -> Path:
        return self.directory / "set.json"


@dataclass(frozen=True)
class ComponentSetsIndex:
    """The parsed ``prompts/sets/index.json``."""

    default_set: str
    union_spec: Path
    core_components: tuple[str, ...]
    panel_components: tuple[str, ...]
    aliases: Mapping[str, str]
    sets: tuple[ComponentSetEntry, ...]

    def get(self, set_id: str) -> ComponentSetEntry | None:
        for entry in self.sets:
            if entry.id == set_id:
                return entry
        return None


@dataclass(frozen=True)
class SetLoadability:
    """The verdict of "can the client render this set?".

    ``checked`` is ``False`` when no union artifact exists (a fresh checkout
    before the generator ran): the store treats a missing artifact as the
    documented fallback path rather than an error, so the check stays permissive
    and says so in ``reason`` instead of refusing a set it cannot judge.
    """

    ok: bool
    unrenderable: tuple[str, ...] = ()
    checked: bool = True
    reason: str = ""


_INDEX_LOCK = threading.Lock()
_INDEX_CACHE: tuple[tuple[Any, ...], ComponentSetsIndex | None] | None = None
_UNION_LOCK = threading.Lock()
_UNION_CACHE: tuple[tuple[Any, ...], dict[str, Any] | None] | None = None


def reset_sets_cache() -> None:
    """Drop the cached index/union (tests repoint ``FABULIST_COMPONENT_SETS_DIR``)."""
    global _INDEX_CACHE, _UNION_CACHE
    with _INDEX_LOCK:
        _INDEX_CACHE = None
    with _UNION_LOCK:
        _UNION_CACHE = None


def _entries(raw: Any) -> tuple[ComponentSetEntry, ...]:
    sets = raw.get("sets") if isinstance(raw, Mapping) else None
    if not isinstance(sets, (list, tuple)):
        return ()
    out: list[ComponentSetEntry] = []
    for item in sets:
        if not isinstance(item, Mapping):
            continue
        set_id = item.get("id")
        if not isinstance(set_id, str) or not set_id.strip():
            continue
        components = item.get("components")
        out.append(
            ComponentSetEntry(
                id=set_id,
                name=str(item.get("name") or set_id),
                version=str(item.get("version") or ""),
                kind=str(item.get("kind") or "shipped"),
                directory=_resolve(item.get("dir") or "."),
                components=tuple(
                    str(name) for name in components if isinstance(name, str)
                )
                if isinstance(components, (list, tuple))
                else (),
                spec_version=str(item.get("spec_version") or ""),
            )
        )
    return tuple(out)


def component_sets_index() -> ComponentSetsIndex | None:
    """The sets registry, or ``None`` when the tree has not been generated."""
    global _INDEX_CACHE
    path = index_path()
    stamp = (path, _stamp(path))
    with _INDEX_LOCK:
        if _INDEX_CACHE is not None and _INDEX_CACHE[0] == stamp:
            return _INDEX_CACHE[1]
    raw = _read_json(path)
    index: ComponentSetsIndex | None = None
    if isinstance(raw, Mapping):
        aliases = raw.get("aliases")
        index = ComponentSetsIndex(
            default_set=str(raw.get("default_set") or "technology"),
            union_spec=_resolve(raw.get("union_spec") or UNION_SPEC_FILENAME),
            core_components=tuple(
                str(name) for name in raw.get("core_components") or () if isinstance(name, str)
            )
            or CORE_COMPONENT_NAMES,
            panel_components=tuple(
                str(name) for name in raw.get("panel_components") or () if isinstance(name, str)
            ),
            aliases={
                str(alias): str(canonical)
                for alias, canonical in (aliases.items() if isinstance(aliases, Mapping) else ())
                if isinstance(canonical, str)
            },
            sets=_entries(raw),
        )
    with _INDEX_LOCK:
        _INDEX_CACHE = (stamp, index)
    return index


def component_sets() -> tuple[ComponentSetEntry, ...]:
    """Every declared set (shipped and fixture), in registry order."""
    index = component_sets_index()
    return index.sets if index is not None else ()


def component_set(set_id: str) -> ComponentSetEntry | None:
    """One declared set by id, or ``None``."""
    index = component_sets_index()
    return index.get(set_id) if index is not None else None


def core_component_names() -> tuple[str, ...]:
    """The never-removable infrastructure components (from the registry)."""
    index = component_sets_index()
    if index is not None and index.core_components:
        return index.core_components
    return CORE_COMPONENT_NAMES


def panel_component_names() -> tuple[str, ...]:
    """Engine-emitted panel surfaces: core, never taught, never in a set.

    ``AssistantCard`` renders through ``panelLibrary.ts``; ``EnvTracker`` through
    ``ChatHud``'s own parser. Neither is a narrator component (ADR-004).
    """
    index = component_sets_index()
    return index.panel_components if index is not None else ()


def render_aliases() -> Mapping[str, str]:
    """Render-only legacy names the client still resolves (never taught)."""
    index = component_sets_index()
    return index.aliases if index is not None else {}


def union_spec() -> dict[str, Any] | None:
    """The union spec (the render contract), or ``None`` when it is absent."""
    global _UNION_CACHE
    # The registry names the union artifact; a tree without a registry (or a
    # hand-written one) falls back to the conventional filename.
    index = component_sets_index()
    path = index.union_spec if index is not None else union_spec_path()
    stamp = (path, _stamp(path))
    with _UNION_LOCK:
        if _UNION_CACHE is not None and _UNION_CACHE[0] == stamp:
            return _UNION_CACHE[1]
    raw = _read_json(path)
    spec = raw if isinstance(raw, Mapping) else None
    with _UNION_LOCK:
        _UNION_CACHE = (stamp, spec)
    return spec


def union_component_names() -> tuple[str, ...]:
    """Every component the client can render, in union-spec order (empty if absent)."""
    spec = union_spec()
    return component_names_in(spec) if spec is not None else ()


def check_set_loadable(components: Iterable[str]) -> SetLoadability:
    """``set ⊆ union`` — the machine-checkable "the client can render it".

    Returns the names the client cannot render (sorted) so a refusal can name
    them; an absent union artifact (fresh checkout) yields a permissive,
    explicitly unchecked verdict — the same fallback discipline the component
    store applies to missing artifacts.
    """
    wanted = tuple(dict.fromkeys(str(name) for name in components))
    union = union_component_names()
    if not union:
        return SetLoadability(
            ok=True,
            checked=False,
            reason=(
                f"{union_spec_path()}: no union spec — run "
                "node frontend/scripts/generate-library-spec.mjs"
            ),
        )
    union_set = set(union)
    unrenderable = tuple(sorted(name for name in wanted if name not in union_set))
    if unrenderable:
        return SetLoadability(
            ok=False,
            unrenderable=unrenderable,
            reason=(
                "the client cannot render "
                + ", ".join(unrenderable)
                + " — a set must be a subset of the union vocabulary "
                f"({union_spec_path()})"
            ),
        )
    return SetLoadability(ok=True)


def set_loadability(entry: ComponentSetEntry) -> SetLoadability:
    """Loadability of one declared set (manifest names, else the spec's names)."""
    components = entry.components
    if not components:
        spec = _read_json(entry.spec_path)
        components = component_names_in(spec) if spec is not None else ()
    return check_set_loadable(components)


def loadable_set_ids() -> tuple[str, ...]:
    """Ids of every declared set the client can render."""
    return tuple(entry.id for entry in component_sets() if set_loadability(entry).ok)


def default_set_id() -> str:
    """The registry's default set id (the resolution floor)."""
    index = component_sets_index()
    if index is not None and index.default_set:
        return index.default_set
    return library_store().snapshot().set_id


def _latest_selected_set_id(log: "EventLog", session_id: str) -> str | None:
    """The latest ``set_swapped`` row's set id in the session's chain, or ``None``.

    Fork-aware (``get_chain_events``): a branch inherits the selection in effect
    when it forked, exactly as it inherits the turns the swap applied to.
    """
    newest: str | None = None
    for event in log.get_chain_events(session_id):
        if event.type != "system" or not isinstance(event.payload, Mapping):
            continue
        payload = event.payload
        if payload.get("event") != SET_SWAP_EVENT:
            continue
        value = payload.get("set_id")
        if isinstance(value, str) and value.strip():
            newest = value
    return newest


def session_set_id(log: "EventLog", session_id: str) -> str:
    """The set id in effect for one session (log fact, else the default)."""
    return _latest_selected_set_id(log, session_id) or default_set_id()


def session_set_entry(
    log: "EventLog", session_id: str
) -> ComponentSetEntry | None:
    """The registry entry for a session's active set (``None`` when undeclared).

    A selected id the registry no longer declares (a set dropped by a
    regeneration) falls back to the default with a warning: an unknown set must
    not strand a session on a prompt it cannot build.
    """
    selected = _latest_selected_set_id(log, session_id)
    if selected is not None:
        entry = component_set(selected)
        if entry is not None:
            return entry
        _LOGGER.warning(
            "session %s selects unknown component set %r; falling back to the default",
            session_id,
            selected,
        )
    return component_set(default_set_id())


def session_snapshot(log: "EventLog", session_id: str) -> ComponentSetSnapshot:
    """Resolve a session's active set from its log and bind it in the store.

    THE per-session resolution seam (issues #16/#24): the narrator builder calls
    this at ``build()`` start, so the taught doc, the gate table and the strip
    list all read one directory for one session. The snapshot itself comes from
    the store's per-directory cache, so two sessions on the same set share one
    snapshot (content is shared; selection is not).
    """
    entry = session_set_entry(log, session_id)
    store = library_store()
    if entry is None:
        store.bind_session_set(session_id, None)
        store.focus_set(None)
        return store.snapshot()
    store.bind_session_set(session_id, entry.directory)
    # Context-local focus: same-task consumers (the taught doc, the gate, the
    # strip list) read this directory even where CURRENT_SESSION is not
    # installed (a prompt preview); the binding above covers sibling tasks.
    store.focus_set(entry.directory)
    return store.snapshot_for_dir(entry.directory)


def active_set_for_session(
    log: "EventLog", session_id: str
) -> ComponentSetSnapshot:
    """Alias of :func:`session_snapshot` (reads best as "the set this turn uses")."""
    return session_snapshot(log, session_id)


def active_set_id_for_session(log: "EventLog", session_id: str) -> str:
    """The set id one session's next turn will be taught."""
    return session_snapshot(log, session_id).set_id


def swap_notice_text(snapshot: ComponentSetSnapshot) -> str:
    """The model-facing announcement frozen into a ``set_swapped`` row.

    Dynamic-tail text only — never the stable prefix (ADR-005). The wording is
    the one the pre-#16 promotion boundary produced, so an existing transcript's
    notice bytes stay comparable across the change.
    """
    return (
        f"The narrator component set is now {snapshot.name} ({snapshot.set_id}). "
        "Use only the components in the current component reference."
    )


def swap_fact(
    previous_set_id: str, snapshot: ComponentSetSnapshot
) -> ComponentSetSwap:
    """The ``set_swapped`` FACT for the selection door to append (D9)."""
    return ComponentSetSwap(
        previous_set_id=previous_set_id,
        set_id=snapshot.set_id,
        name=snapshot.name,
        version=snapshot.version,
    )


def active_set() -> ComponentSetSnapshot:
    """The set resolved for the CURRENT context (the model-facing one).

    Off-turn (no session context) this is env override → default. During a turn
    it is the session binding installed by :func:`session_snapshot`.
    """
    return library_store().snapshot()


def active_set_id() -> str:
    """Id of the active set (what the taught doc, gate and strip list read)."""
    return active_set().set_id


def active_set_unrenderable() -> tuple[str, ...]:
    """Components the ACTIVE set declares that the client cannot render.

    Empty for every shipped configuration; a non-empty answer is the one thing a
    selection surface must refuse (#16) and an operator should never see from a
    generated tree.
    """
    snapshot = active_set()
    if snapshot.spec is None:
        return ()
    return check_set_loadable(component_names_in(snapshot.spec)).unrenderable
